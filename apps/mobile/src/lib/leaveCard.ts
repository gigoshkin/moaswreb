// Android "leave card": an ongoing notification that appears 30 min before
// the leave time and counts down by itself (the system chronometer), then
// turns into "Leave now" at the leave time and goes away 10 min later. A
// progress bar spans leave time to arrival.
//
// The card is live: the AlarmManager trigger at 30 min before starts it as a
// foreground service (notify-kit asForegroundService; the service type is
// declared in app.json). Its runner (runLive) looks at the plan every 30 s and
// re-posts the same notification when the leave time moves, the line runs
// late and another is clearly better ("switch to 17"), or the progress bar
// moves, until 10 min after the leave time.
//
// Fallback: the static card, as before. A second countdown trigger fires a
// minute later and the service cancels it as soon as it runs, so it only
// shows when the service could not start (Android 12+ only lets an app start
// a foreground service from the background in a few cases; an exact alarm is
// one, so with "Alarms & reminders" off the service does not start). The
// "Leave now" part is a plain trigger too and is cancelled once the service
// runs. Needs the dev build (react-native-notify-kit is native); in Expo Go,
// on iOS and on the web every function here does nothing.

type NotifyKit = typeof NotifyKitModule;

/** Lazily required: the module's TurboModule throws in Expo Go and does not exist on the web. */
const kit: NotifyKit | null = (() => {
  if (Platform.OS !== 'android' || isExpoGo) return null;
  try {
    return require('react-native-notify-kit') as NotifyKit;
  } catch {
    return null;
  }
})();
const notifee = kit?.default ?? null;

const CHANNEL = 'leave-card';
/** One card at a time: the next trip. The two parts are separate notifications (one trigger each). */
const CARD = 'leave-card';
const NOW = 'leave-card-now';
/** The static countdown that shows when the service did not take over. */
const FALLBACK = 'leave-card-static';
const TEST_CARD = 'leave-card-test';
const TEST_NOW = 'leave-card-test-now';
const TEST_FALLBACK = 'leave-card-test-static';
/** Generated by the react-native-notify-kit config plugin (app.json). Missing: the app icon is used. */
const ICON = 'ic_leave_card';
const LAST_KEY = 'leaveCard:last';
/** Trip days (`id|date`) whose leave time has passed: the user has left, so no card for a later bus that day. */
const DONE_KEY = 'leaveCard:done';
/** What the service reported last (LiveRecord), so the app's sync leaves a running card alone. */
const LIVE_KEY = 'leaveCard:live';
/** The planned first ride and when it first showed up, to tell a delay from a different run (Watch, per trip and day). */
const WATCH_KEY = 'leaveCard:watch';

interface Last {
  key: string;
  trip: string;
  date: string;
  leaveAt: number;
}
/** Plans for a trip the Today screen hasn't loaded (e.g. tomorrow's): fetched at most this often. */
const FETCH_EVERY_MS = 10 * 60_000;

export const leaveCardAvailable = notifee !== null;

/** Opens the trip when the user taps the leave card (cold start or app already running). Returns an unsubscribe. */
export function onLeaveCardTap(open: (tripId: string) => void): () => void {
  if (!notifee || !kit) return () => {};
  const handle = (n?: Notification | null) => {
    const tripId = n?.data?.tripId;
    if (typeof tripId === 'string') open(tripId);
  };
  notifee.getInitialNotification().then((i) => handle(i?.notification)).catch(() => {});
  return notifee.onForegroundEvent(({ type, detail }) => {
    if (type === kit.EventType.PRESS) handle(detail.notification);
  });
}

/** The trip the card is for: the same rule as Today's hero (today's next arrive-by), else the next day that has one. */
function nextTrip(trips: SavedTrip[], now: number, done: string[]): { trip: SavedTrip; date: string } | null {
  const today = todayLocal(now);
  const clock = hhmm(now);
  for (let i = 0; i <= 7; i++) {
    const date = addDays(today, i);
    const trip = trips
      .filter((t) => tripDays(t).includes(isoWeekday(date)) && (i > 0 || t.arriveBy > clock) && !done.includes(`${t.id}|${date}`))
      .sort((a, b) => a.arriveBy.localeCompare(b.arriveBy))[0];
    if (trip) return { trip, date };
  }
  return null;
}

const lastFetch = new Map<string, number>();

interface Card {
  input: CardInput;
  minibus: boolean;
  /** Every option of the plan, for spotting a better line. */
  its: Itinerary[];
}

/**
 * The chosen option for the trip (plans.choose, with the user's buffer), as card input.
 * The app fetches a missing plan while it is open; the service (`every` set) refreshes it that often.
 */
async function cardFor(trip: SavedTrip, date: string, now: number, every?: number): Promise<Card | null> {
  if (!hasApi) return null;
  // Every way the trip keeps, merged (one query each, as the trip screen plans them).
  const qs = tripQueries(trip, date);
  const q = qs[0];
  const plans = await Promise.all(
    qs.map(async (one) => {
      const key = JSON.stringify(one);
      let p = cachedPlan(one);
      const fetchNow = every !== undefined ? now - (lastFetch.get(key) ?? 0) >= every : !p && AppState.currentState === 'active' && now - (lastFetch.get(key) ?? 0) > FETCH_EVERY_MS;
      if (fetchNow) {
        lastFetch.set(key, now);
        p = (await fetchPlan(one).catch(() => null)) ?? p;
      }
      return p;
    }),
  );
  const plan = mergePlans(plans.flatMap((p) => p ?? []));
  if (!plan) return null;
  const c = choose(plan.itineraries, q.arriveBy, now, settings.get().bufferMin);
  if (c.kind === 'none') return null;
  const first = transitLegs(c.it)[0];
  return {
    minibus: Boolean(first?.route?.minibus),
    its: plan.itineraries,
    input: {
      tripName: trip.name,
      leaveAt: c.leaveAt,
      arriveAt: Date.parse(c.it.arriveAt),
      late: c.kind === 'late',
      ride: first
        ? { mode: first.mode, line: first.route?.shortName ?? null, departAt: Date.parse(first.departAt), stop: first.from.name || null, live: first.realtime }
        : null,
    },
  };
}

/** Shared by every part of the card (static and live). */
function baseAndroid(body: string, leaveAt: number) {
  if (!kit) throw new Error('no notify-kit');
  const { AndroidImportance, AndroidStyle, AndroidVisibility, AndroidCategory } = kit;
  return {
    channelId: CHANNEL,
    smallIcon: ICON,
    importance: AndroidImportance.HIGH,
    category: AndroidCategory.REMINDER,
    visibility: AndroidVisibility.PUBLIC,
    ongoing: true,
    autoCancel: false,
    showTimestamp: true,
    timestamp: leaveAt,
    showChronometer: true,
    style: { type: AndroidStyle.BIGTEXT, text: body } as const,
    pressAction: { id: 'default', launchActivity: 'default' },
  };
}

interface Ids {
  card: string;
  now: string;
  fallback: string;
}

function parts(ids: Ids, tripId: string, title: string, leaveNowTitle: string, body: string, t: CardTimes, arriveAt: number) {
  const base = baseAndroid(body, t.leaveAt);
  // The bar is fixed at what is true when the part is posted (a part scheduled for later starts at its own time):
  // nothing redraws it between the card's triggers. The live card (below) redraws it.
  const bar = (at: number) => {
    const p = cardProgress(t.leaveAt, arriveAt, at);
    return p ? { progress: p } : {};
  };
  const countdown: Notification = {
    id: ids.card,
    title,
    body,
    data: { tripId, leaveAt: String(t.leaveAt) },
    // Counts down to the leave time in the header (and, on Android 16+, would in a Live Update chip).
    // Gone at the leave time, when the "Leave now" part takes over.
    android: { ...base, ...bar(t.showAt), chronometerDirection: 'down', onlyAlertOnce: true, timeoutAfter: Math.max(1_000, t.leaveAt - t.showAt) },
  };
  const leaveNow: Notification = {
    id: ids.now,
    title: leaveNowTitle,
    body,
    data: { tripId, leaveAt: String(t.leaveAt) },
    // Counts up from the leave time ("02:10" late), gone once the user has surely left.
    android: { ...base, ...bar(Math.max(t.leaveAt, Date.now())), chronometerDirection: 'up', onlyAlertOnce: false, timeoutAfter: Math.max(1_000, t.endAt - Math.max(t.leaveAt, Date.now())) },
  };
  // Posted a minute after the live card was due; the service cancels it when it runs.
  const fallback: Notification = { ...countdown, id: ids.fallback, android: { ...countdown.android, timeoutAfter: Math.max(1_000, t.leaveAt - t.showAt - FALLBACK_AFTER_MS) } };
  return { countdown, leaveNow, fallback };
}

/** What the service needs to run the card on its own, carried in the notification's data. */
interface LiveRun {
  trip: string;
  date: string;
  /** The plan the card was set up with; the service uses it until a fresher one comes in. */
  input: CardInput;
  minibus: boolean;
  /** The part after the leave time stays this long. */
  keepMs: number;
  /** The static parts to cancel once the service runs. */
  nowId: string;
  fallbackId: string;
  /** A fake plan (Settings, dev): nothing is read from or written to the app's state. */
  test: boolean;
}

/** The card as a foreground-service notification: same id for every update, so the service re-posts it in place. */
function liveNotification(id: string, run: LiveRun, v: LiveView, alert: boolean): Notification {
  if (!kit) throw new Error('no notify-kit');
  return {
    id,
    title: v.title,
    body: v.body,
    data: { tripId: run.trip, leaveAt: String(v.leaveAt), live: JSON.stringify(run) },
    android: {
      ...baseAndroid(v.body, v.leaveAt),
      asForegroundService: true,
      // Must be among the types declared in app.json (plugin option android.foregroundService.types).
      foregroundServiceTypes: [kit.AndroidForegroundServiceType.FOREGROUND_SERVICE_TYPE_DATA_SYNC],
      chronometerDirection: v.leaving ? 'up' : 'down',
      onlyAlertOnce: !alert,
      ...(v.progress === null ? {} : { progress: { max: 100, current: v.progress } }),
    },
  };
}

/** displayNotification / createTriggerNotification, retried without the custom icon if the build lacks it. */
async function post(n: Notification, at: number | null): Promise<void> {
  if (!notifee || !kit) return;
  const send = (x: Notification) =>
    at === null
      ? notifee.displayNotification(x)
      : notifee.createTriggerNotification(x, {
          type: kit.TriggerType.TIMESTAMP,
          timestamp: at,
          // Exact when "Alarms & reminders" is allowed; otherwise notify-kit falls back to an inexact alarm (can be minutes late in Doze).
          alarmManager: { type: kit.AlarmType.SET_EXACT_AND_ALLOW_WHILE_IDLE },
        });
  try {
    await send(n);
  } catch {
    await send({ ...n, android: { ...n.android, smallIcon: undefined } });
  }
}

/** The live card, now (`at` null) or at `at`. False when it could not be posted (the caller falls back to the static card). */
async function postLive(n: Notification, at: number | null): Promise<boolean> {
  try {
    await post(n, at);
    return true;
  } catch {
    return false;
  }
}

/** The countdown part as the live card, with the static fallback and the "Leave now" part scheduled behind it. */
async function schedule(ids: Ids, run: LiveRun, t: CardTimes, now: number): Promise<void> {
  const { input } = run;
  const text = cardText(input, hhmm, run.minibus);
  const { countdown, leaveNow, fallback } = parts(ids, run.trip, text.title, text.leaveNowTitle, text.body, t, input.arriveAt);
  const live = liveNotification(ids.card, run, liveView(input, run.minibus, null, now, hhmm), false);
  if (t.showNow) {
    // The app is open, so the service may start. If it can't, the static card.
    if (!(await postLive(live, null))) await post(countdown, null);
  } else if (await postLive(live, t.showAt)) {
    await post(fallback, t.showAt + FALLBACK_AFTER_MS);
  } else {
    await post(countdown, t.showAt);
  }
  await post(leaveNow, t.leaveAt);
}

async function show(ids: Ids, trip: SavedTrip, date: string, input: CardInput, minibus: boolean, now: number): Promise<boolean> {
  const t = cardTimes(input.leaveAt, now);
  if (!t) return false;
  if (now < t.leaveAt) {
    await schedule(ids, { trip: trip.id, date, input, minibus, keepMs: KEEP_AFTER_MS, nowId: ids.now, fallbackId: ids.fallback, test: false }, t, now);
  } else {
    const text = cardText(input, hhmm, minibus);
    const { leaveNow } = parts(ids, trip.id, text.title, text.leaveNowTitle, text.body, t, input.arriveAt);
    await notifee?.cancelNotification(ids.card);
    await post(leaveNow, null);
  }
  return true;
}

async function clear(ids: string[]): Promise<void> {
  if (!notifee) return;
  await notifee.cancelTriggerNotifications(ids).catch(() => {});
  for (const id of ids) await notifee.cancelNotification(id).catch(() => {});
}

/** Stops the foreground service (its runner sees the card is gone and ends). */
async function stopLive(): Promise<void> {
  const live = readCache<LiveRecord>(LIVE_KEY);
  if (live && !live.ended) writeCache(LIVE_KEY, { ...live, ended: 'cancelled' } satisfies LiveRecord);
  await notifee?.stopForegroundService().catch(() => {});
}

const tripDay = (trip: string, date: string) => `${trip}|${date}`;

/** Never offer a later bus for this trip and day. */
function markDone(trip: string, date: string): void {
  const done = readCache<string[]>(DONE_KEY) ?? [];
  const id = tripDay(trip, date);
  if (!done.includes(id)) writeCache(DONE_KEY, [id, ...done].slice(0, 20));
}

interface WatchRecord {
  trip: string;
  date: string;
  watch: Watch;
}

/** The ride a delay is measured against for this trip and day: kept while the plan keeps that run (nextWatch). */
function trackWatch(trip: string, date: string, ride: CardInput['ride'], now: number): Watch | null {
  const prev = readCache<WatchRecord>(WATCH_KEY);
  const before = prev && prev.trip === trip && prev.date === date ? prev.watch : null;
  const watch = nextWatch(before, ride ? { line: ride.line, departAt: ride.departAt } : null, now);
  if (watch?.line !== before?.line || watch?.departAt !== before?.departAt) writeCache(WATCH_KEY, watch ? ({ trip, date, watch } satisfies WatchRecord) : null);
  return watch;
}

/**
 * Schedule, replace or remove the card for the next trip's current plan.
 * Re-posts only when the plan's leave time or text changed.
 */
async function sync(now = Date.now()): Promise<void> {
  if (!notifee) return;
  const live = readCache<LiveRecord>(LIVE_KEY);
  const status = liveStatus(live, now);
  // The service owns the card while it reports; it updates the plan itself.
  if (status === 'running') return;
  const { alerts } = settings.get();
  const trips = tripsStore.get();
  let last = readCache<Last>(LAST_KEY);
  let done = readCache<string[]>(DONE_KEY) ?? [];
  if (status === 'stale') {
    // The service stopped without a word (the process was killed): post the card again.
    writeCache(LIVE_KEY, null);
    writeCache(LAST_KEY, (last = null));
  }
  if (last && now >= last.leaveAt) {
    // The card reached "Leave now": let it play out, and never offer a later bus for that trip and day.
    const id = tripDay(last.trip, last.date);
    if (!done.includes(id)) writeCache(DONE_KEY, (done = [id, ...done].slice(0, 20)));
    if (alerts && now < last.leaveAt + KEEP_AFTER_MS && trips.some((t) => t.id === last.trip)) return;
  }
  const next = alerts ? nextTrip(trips, now, done) : null;
  const card = next ? await cardFor(next.trip, next.date, now) : null;
  if (!next || !card || !cardTimes(card.input.leaveAt, now)) {
    if (last) {
      writeCache(LAST_KEY, null);
      await stopLive();
      await clear([CARD, NOW, FALLBACK]);
    }
    return;
  }
  // Swiped away (Android 14+ lets the user dismiss a foreground-service card): not again for this trip and day.
  if (live?.ended === 'dismissed' && live.trip === next.trip.id && live.date === next.date) return;
  trackWatch(next.trip.id, next.date, card.input.ride, now);
  const key = cardKey(next.trip.id, card.input, cardText(card.input, hhmm, card.minibus));
  if (key === last?.key) return;
  // Pending triggers go first; a card already on screen is updated in place by id (onlyAlertOnce: no second buzz).
  await notifee.cancelTriggerNotifications([CARD, NOW, FALLBACK]).catch(() => {});
  if (await show({ card: CARD, now: NOW, fallback: FALLBACK }, next.trip, next.date, card.input, card.minibus, now)) {
    writeCache(LAST_KEY, { key, trip: next.trip.id, date: next.date, leaveAt: card.input.leaveAt } satisfies Last);
  }
}

/** Cards the user swiped away (Android 14+ allows it for a foreground-service card), by notification id. */
const dismissed = new Set<string>();
const sleep = (ms: number) => new Promise<void>((resolve) => setTimeout(resolve, ms));

/** The test card's fake plan: 539 runs late a minute and a half before the leave time and 17 is better. */
const fakeSwitch = (run: LiveRun, now: number): Switch | null =>
  now >= run.input.leaveAt - 90_000 ? { fromLine: '539', toLine: '17', lateMin: 4, leaveAt: run.input.leaveAt + 90_000, arriveAt: run.input.arriveAt - 5 * 60_000 } : null;

/**
 * The foreground service's runner: the service lives as long as the promise
 * it returns. Looks at the plan every 30 s and re-posts the card (same id)
 * when something visible changed; ends 10 min after the leave time, when the
 * card is swiped away, or when the trip or the alerts are gone.
 */
async function runLive(n: Notification): Promise<void> {
  if (!notifee) return;
  const id = n.id ?? CARD;
  let run: LiveRun;
  try {
    run = JSON.parse(String(n.data?.live)) as LiveRun;
  } catch {
    return;
  }
  // The service has taken over: the static fallback and the static "Leave now" part must not fire too.
  await notifee.cancelTriggerNotifications([run.fallbackId, run.nowId]).catch(() => {});
  dismissed.delete(id);
  const record = (ended?: LiveRecord['ended']) => !run.test && writeCache(LIVE_KEY, { trip: run.trip, date: run.date, beat: Date.now(), ...(ended ? { ended } : {}) } satisfies LiveRecord);
  // Someone else (cancelLeaveCard, sync) ended it while this was waiting.
  const stopped = () => !run.test && Boolean(readCache<LiveRecord>(LIVE_KEY)?.ended);
  record();

  let { input, minibus } = run;
  let sw: Switch | null = null;
  let view: LiveView | null = null;
  let ended: NonNullable<LiveRecord['ended']> = 'finished';
  let failures = 0;
  try {
    for (;;) {
      const trip = run.test ? null : tripsStore.get().find((t) => t.id === run.trip);
      if (!run.test && (!settings.get().alerts || !trip)) {
        ended = 'cancelled';
        break;
      }
      if (stopped()) {
        ended = 'cancelled';
        break;
      }
      record();
      // Until the leave time the plan is followed; after it the card only plays out (choose would offer the next bus).
      if (Date.now() < (view?.leaveAt ?? input.leaveAt)) {
        if (run.test) {
          sw = fakeSwitch(run, Date.now());
        } else if (trip) {
          const card = await cardFor(trip, run.date, Date.now(), LIVE_FETCH_EVERY_MS);
          if (card) {
            input = card.input;
            minibus = card.minibus;
            const watch = trackWatch(trip.id, run.date, input.ride, Date.now());
            sw = watch ? findSwitch(card.its, watch, Date.now(), settings.get().bufferMin) : null;
          }
        }
      }
      const now = Date.now();
      if (dismissed.has(id)) {
        ended = 'dismissed';
        break;
      }
      if (stopped()) {
        ended = 'cancelled';
        break;
      }
      const next = liveView(input, minibus, sw, now, hhmm);
      if (now >= next.leaveAt + run.keepMs) break;
      if (viewChanged(view, next)) {
        if (await postLive(liveNotification(id, run, next, shouldAlert(view, next)), null)) {
          failures = 0;
          view = next;
        } else if (++failures >= 2) {
          // The system no longer lets the service post (it was stopped): the static parts are gone, so be done.
          ended = 'cancelled';
          break;
        }
      }
      if (next.leaving && !run.test) markDone(run.trip, run.date);
      await sleep(nextLookIn(Date.now(), next.leaveAt, next.leaveAt + run.keepMs));
    }
  } finally {
    record(ended);
    if (!run.test && ended === 'finished') {
      markDone(run.trip, run.date);
      writeCache(LAST_KEY, null);
    }
    await notifee.stopForegroundService().catch(() => {});
    if (ended !== 'dismissed') await notifee.cancelNotification(id).catch(() => {});
  }
}

if (notifee && kit) {
  notifee.registerForegroundService(runLive);
  const onEvent = async ({ type, detail }: Event) => {
    if (type === kit.EventType.DISMISSED && detail.notification?.id) dismissed.add(detail.notification.id);
  };
  notifee.onBackgroundEvent(onEvent);
  notifee.onForegroundEvent(onEvent);
}

let queue: Promise<void> = Promise.resolve();
/** Runs syncs one at a time, so a cancel never races a create. */
export const syncLeaveCard = (): Promise<void> => (queue = queue.then(() => sync()).catch(() => {}));

let started = false;
/**
 * Keeps the card in step with trips, settings and plans: on every trip or
 * settings change, every minute while the app runs (Today's refresh updates
 * the cached plan) and when the app comes back. Call after notification
 * permission is granted. Safe to call more than once.
 */
export async function startLeaveCard(): Promise<void> {
  if (!notifee || started) return;
  started = true;
  await notifee.createChannel({ id: CHANNEL, name: 'Leave countdown', importance: kit!.AndroidImportance.HIGH, visibility: kit!.AndroidVisibility.PUBLIC }).catch(() => {});
  const run = () => void syncLeaveCard();
  tripsStore.subscribe(run);
  settings.subscribe(run);
  setInterval(run, 60_000);
  AppState.addEventListener('change', (s) => s === 'active' && run());
  run();
}

/** Alerts off in Settings or data deleted: no card. */
export async function cancelLeaveCard(): Promise<void> {
  writeCache(LAST_KEY, null);
  await stopLive();
  await clear([CARD, NOW, FALLBACK]);
}

