// Android "leave card": an ongoing notification that appears 30 min before
// the leave time and counts down by itself (the system chronometer, no app
// wake-ups), then turns into "Leave now" at the leave time and goes away
// 10 min later. Both parts are scheduled as AlarmManager triggers, so they
// fire with the app closed. Needs the dev build (react-native-notify-kit is
// native); in Expo Go, on iOS and on the web every function here does nothing.

type NotifyKit = typeof NotifyKitModule;

/** Lazily required: the module's TurboModule throws in Expo Go and does not exist on the web. */
const kit: NotifyKit | null = (() => {
  if (Platform.OS !== 'android' || isExpoGo) return null;
  try {
    return require('react-native-notify-kit') as NotifyKit;
  } catch {
    return null;
  }
})();
const notifee = kit?.default ?? null;

const CHANNEL = 'leave-card';
/** One card at a time: the next trip. The two parts are separate notifications (one trigger each). */
const CARD = 'leave-card';
const NOW = 'leave-card-now';
const TEST_CARD = 'leave-card-test';
const TEST_NOW = 'leave-card-test-now';
/** Generated by the react-native-notify-kit config plugin (app.json). Missing: the app icon is used. */
const ICON = 'ic_leave_card';
const LAST_KEY = 'leaveCard:last';
/** Trip days (`id|date`) whose leave time has passed: the user has left, so no card for a later bus that day. */
const DONE_KEY = 'leaveCard:done';

interface Last {
  key: string;
  trip: string;
  date: string;
  leaveAt: number;
}
/** Plans for a trip the Today screen hasn't loaded (e.g. tomorrow's): fetched at most this often. */
const FETCH_EVERY_MS = 10 * 60_000;

export const leaveCardAvailable = notifee !== null;

/** Opens the trip when the user taps the leave card (cold start or app already running). Returns an unsubscribe. */
export function onLeaveCardTap(open: (tripId: string) => void): () => void {
  if (!notifee || !kit) return () => {};
  const handle = (n?: Notification | null) => {
    const tripId = n?.data?.tripId;
    if (typeof tripId === 'string') open(tripId);
  };
  notifee.getInitialNotification().then((i) => handle(i?.notification)).catch(() => {});
  return notifee.onForegroundEvent(({ type, detail }) => {
    if (type === kit.EventType.PRESS) handle(detail.notification);
  });
}

/** The trip the card is for: the same rule as Today's hero (today's next arrive-by), else the next day that has one. */
function nextTrip(trips: SavedTrip[], now: number, done: string[]): { trip: SavedTrip; date: string } | null {
  const today = todayLocal(now);
  const clock = hhmm(now);
  for (let i = 0; i <= 7; i++) {
    const date = addDays(today, i);
    const trip = trips
      .filter((t) => tripDays(t).includes(isoWeekday(date)) && (i > 0 || t.arriveBy > clock) && !done.includes(`${t.id}|${date}`))
      .sort((a, b) => a.arriveBy.localeCompare(b.arriveBy))[0];
    if (trip) return { trip, date };
  }
  return null;
}

const lastFetch = new Map<string, number>();

/** The chosen option for the trip (plans.choose, with the user's buffer), as card input. */
async function cardFor(trip: SavedTrip, date: string, now: number): Promise<{ input: CardInput; minibus: boolean } | null> {
  if (!hasApi) return null;
  // Every way the trip keeps, merged (one query each, as the trip screen plans them).
  const qs = tripQueries(trip, date);
  const q = qs[0];
  const plans = await Promise.all(
    qs.map(async (one) => {
      const key = JSON.stringify(one);
      let p = cachedPlan(one);
      if (!p && AppState.currentState === 'active' && now - (lastFetch.get(key) ?? 0) > FETCH_EVERY_MS) {
        lastFetch.set(key, now);
        p = await fetchPlan(one).catch(() => null);
      }
      return p;
    }),
  );
  const plan = mergePlans(plans.flatMap((p) => p ?? []));
  if (!plan) return null;
  const c = choose(plan.itineraries, q.arriveBy, now, settings.get().bufferMin);
  if (c.kind === 'none') return null;
  const first = transitLegs(c.it)[0];
  return {
    minibus: Boolean(first?.route?.minibus),
    input: {
      tripName: trip.name,
      leaveAt: c.leaveAt,
      arriveAt: Date.parse(c.it.arriveAt),
      late: c.kind === 'late',
      ride: first
        ? { mode: first.mode, line: first.route?.shortName ?? null, departAt: Date.parse(first.departAt), stop: first.from.name || null, live: first.realtime }
        : null,
    },
  };
}

function parts(ids: { card: string; now: string }, tripId: string, title: string, leaveNowTitle: string, body: string, t: CardTimes) {
  if (!kit) throw new Error('no notify-kit');
  const { AndroidImportance, AndroidStyle, AndroidVisibility, AndroidCategory } = kit;
  const base = {
    channelId: CHANNEL,
    smallIcon: ICON,
    importance: AndroidImportance.HIGH,
    category: AndroidCategory.REMINDER,
    visibility: AndroidVisibility.PUBLIC,
    ongoing: true,
    autoCancel: false,
    showTimestamp: true,
    timestamp: t.leaveAt,
    showChronometer: true,
    style: { type: AndroidStyle.BIGTEXT, text: body } as const,
    pressAction: { id: 'default', launchActivity: 'default' },
  };
  const countdown: Notification = {
    id: ids.card,
    title,
    body,
    data: { tripId, leaveAt: String(t.leaveAt) },
    // Counts down to the leave time in the header (and, on Android 16+, would in a Live Update chip).
    // Gone at the leave time, when the "Leave now" part takes over.
    android: { ...base, chronometerDirection: 'down', onlyAlertOnce: true, timeoutAfter: Math.max(1_000, t.leaveAt - t.showAt) },
  };
  const leaveNow: Notification = {
    id: ids.now,
    title: leaveNowTitle,
    body,
    data: { tripId, leaveAt: String(t.leaveAt) },
    // Counts up from the leave time ("02:10" late), gone once the user has surely left.
    android: { ...base, chronometerDirection: 'up', onlyAlertOnce: false, timeoutAfter: Math.max(1_000, t.endAt - Math.max(t.leaveAt, Date.now())) },
  };
  return { countdown, leaveNow };
}

/** displayNotification / createTriggerNotification, retried without the custom icon if the build lacks it. */
async function post(n: Notification, at: number | null): Promise<void> {
  if (!notifee || !kit) return;
  const send = (x: Notification) =>
    at === null
      ? notifee.displayNotification(x)
      : notifee.createTriggerNotification(x, {
          type: kit.TriggerType.TIMESTAMP,
          timestamp: at,
          // Exact when "Alarms & reminders" is allowed; otherwise notify-kit falls back to an inexact alarm (can be minutes late in Doze).
          alarmManager: { type: kit.AlarmType.SET_EXACT_AND_ALLOW_WHILE_IDLE },
        });
  try {
    await send(n);
  } catch {
    await send({ ...n, android: { ...n.android, smallIcon: undefined } });
  }
}

async function show(ids: { card: string; now: string }, tripId: string, input: CardInput, minibus: boolean, now: number): Promise<boolean> {
  const t = cardTimes(input.leaveAt, now);
  if (!t) return false;
  const text = cardText(input, hhmm, minibus);
  const { countdown, leaveNow } = parts(ids, tripId, text.title, text.leaveNowTitle, text.body, t);
  if (now < t.leaveAt) {
    await post(countdown, t.showNow ? null : t.showAt);
    await post(leaveNow, t.leaveAt);
  } else {
    await notifee?.cancelNotification(ids.card);
    await post(leaveNow, null);
  }
  return true;
}

async function clear(ids: string[]): Promise<void> {
  if (!notifee) return;
  await notifee.cancelTriggerNotifications(ids).catch(() => {});
  for (const id of ids) await notifee.cancelNotification(id).catch(() => {});
}

/**
 * Schedule, replace or remove the card for the next trip's current plan.
 * Re-posts only when the plan's leave time or text changed.
 */
async function sync(now = Date.now()): Promise<void> {
  if (!notifee) return;
  const { alerts } = settings.get();
  const trips = tripsStore.get();
  const last = readCache<Last>(LAST_KEY);
  let done = readCache<string[]>(DONE_KEY) ?? [];
  if (last && now >= last.leaveAt) {
    // The card reached "Leave now": let it play out, and never offer a later bus for that trip and day.
    const id = `${last.trip}|${last.date}`;
    if (!done.includes(id)) writeCache(DONE_KEY, (done = [id, ...done].slice(0, 20)));
    if (alerts && now < last.leaveAt + KEEP_AFTER_MS && trips.some((t) => t.id === last.trip)) return;
  }
  const next = alerts ? nextTrip(trips, now, done) : null;
  const card = next ? await cardFor(next.trip, next.date, now) : null;
  if (!next || !card || !cardTimes(card.input.leaveAt, now)) {
    if (last) {
      writeCache(LAST_KEY, null);
      await clear([CARD, NOW]);
    }
    return;
  }
  const key = cardKey(next.trip.id, card.input, cardText(card.input, hhmm, card.minibus));
  if (key === last?.key) return;
  // Pending triggers go first; a card already on screen is updated in place by id (onlyAlertOnce: no second buzz).
  await notifee.cancelTriggerNotifications([CARD, NOW]).catch(() => {});
  if (await show({ card: CARD, now: NOW }, next.trip.id, card.input, card.minibus, now)) {
    writeCache(LAST_KEY, { key, trip: next.trip.id, date: next.date, leaveAt: card.input.leaveAt } satisfies Last);
  }
}

let queue: Promise<void> = Promise.resolve();
/** Runs syncs one at a time, so a cancel never races a create. */
export const syncLeaveCard = (): Promise<void> => (queue = queue.then(() => sync()).catch(() => {}));

let started = false;
/**
 * Keeps the card in step with trips, settings and plans: on every trip or
 * settings change, every minute while the app runs (Today's refresh updates
 * the cached plan) and when the app comes back. Call after notification
 * permission is granted. Safe to call more than once.
 */
export async function startLeaveCard(): Promise<void> {
  if (!notifee || started) return;
  started = true;
  await notifee.createChannel({ id: CHANNEL, name: 'Leave countdown', importance: kit!.AndroidImportance.HIGH, visibility: kit!.AndroidVisibility.PUBLIC }).catch(() => {});
  const run = () => void syncLeaveCard();
  tripsStore.subscribe(run);
  settings.subscribe(run);
  setInterval(run, 60_000);
  AppState.addEventListener('change', (s) => s === 'active' && run());
  run();
}

/** Alerts off in Settings or data deleted: no card. */
export async function cancelLeaveCard(): Promise<void> {
  writeCache(LAST_KEY, null);
  await clear([CARD, NOW]);
}

/**
 * Dev only (Settings, __DEV__): a test card that appears in 1 min, says
 * "Leave now" at 3 min and goes away at 5 min. Returns a line for a dialog.
 */
export async function testLeaveCard(): Promise<string> {
  if (!notifee || !kit) return 'Leave card needs the Android dev build (not Expo Go, iOS or web).';
  await startLeaveCard();
  const settingsNow = await notifee.getNotificationSettings();
  const now = Date.now();
  const input: CardInput = {
    tripName: 'Test',
    leaveAt: now + 3 * 60_000,
    arriveAt: now + 45 * 60_000,
    late: false,
    ride: { mode: 'BUS', line: '539', departAt: now + 9 * 60_000, stop: 'Rustaveli Ave', live: false },
  };
  await clear([TEST_CARD, TEST_NOW]);
  // Shorter than the real card: show 2 min before the leave time, keep 2 min after.
  const t: CardTimes = { showAt: now + 60_000, leaveAt: input.leaveAt, endAt: input.leaveAt + Math.min(KEEP_AFTER_MS, 2 * 60_000), showNow: false };
  const text = cardText(input, hhmm);
  const { countdown, leaveNow } = parts({ card: TEST_CARD, now: TEST_NOW }, 'test', text.title, text.leaveNowTitle, text.body, t);
  await post(countdown, t.showAt);
  await post(leaveNow, t.leaveAt);
  const exact = settingsNow.android.alarm === kit.AndroidNotificationSetting.ENABLED;
  const allowed = settingsNow.authorizationStatus === kit.AuthorizationStatus.AUTHORIZED;
  return [
    `Card at ${hhmm(t.showAt)}, "Leave now" at ${hhmm(t.leaveAt)}, gone at ${hhmm(t.endAt)}. Lock the phone to see it.`,
    allowed ? '' : 'Notifications are not allowed for this app.',
    exact ? '' : 'Exact alarms are off, so it may come late: allow "Alarms & reminders" for the app.',
  ]
    .filter(Boolean)
    .join('\n');
}

/** Opens Android's "Alarms & reminders" page for this app (exact timing). */
export const openExactAlarmSettings = () => notifee?.openAlarmPermissionSettings().catch(() => {});

/** True when exact alarms are allowed (Android 12+ asks the user). Null when the card isn't available. */
export async function exactAlarmsAllowed(): Promise<boolean | null> {
  if (!notifee || !kit) return null;
  const s = await notifee.getNotificationSettings().catch(() => null);
  return s ? s.android.alarm === kit.AndroidNotificationSetting.ENABLED : null;
}
