// Builds src/ui/icons.generated.ts from assets/icons/*.svg (exported from
// andro's Figma, plus a few drawn in the same style). Colours become
// currentColor so <Icon color> can tint them. Run: node scripts/icons.mjs
import fs from 'node:fs';
import path from 'node:path';

const dir = path.join(import.meta.dirname, '../assets/icons');
const out = path.join(import.meta.dirname, '../src/ui/icons.generated.ts');
const entries = fs
  .readdirSync(dir)
  .filter((f) => f.endsWith('.svg'))
  .sort()
  .map((f) => {
    const xml = fs
      .readFileSync(path.join(dir, f), 'utf8')
      .replace(/ (preserveAspectRatio|overflow|style|id)="[^"]*"/g, '')
      .replace(/(stroke|fill)="(?!none)[^"]*"/g, '$1="currentColor"')
      .replace(/\s*\n\s*/g, '');
    const size = Number(/width="(\d+)"/.exec(xml)[1]);
    return `  '${f.slice(0, -4)}': { size: ${size}, xml: '${xml}' },`;
  });
fs.writeFileSync(out, `// Generated by scripts/icons.mjs from assets/icons. Do not edit.\n\nexport const icons = {\n${entries.join('\n')}\n} as const;\n`);
console.log(`${entries.length} icons → ${path.relative(process.cwd(), out)}`);
